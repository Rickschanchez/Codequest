package com.codequest.app.data.auth

import android.content.Context
import android.content.res.Resources
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.gms.tasks.Task
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.auth.AuthResult
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseAuthException
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import com.google.firebase.auth.UserProfileChangeRequest
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.suspendCancellableCoroutine
import kotlin.coroutines.resume
import kotlin.coroutines.resumeWithException

/**
 * Firebase-backed implementation of [AuthRepository].
 *
 * Firebase is initialised lazily and defensively: without google-services.json
 * the Google Services plugin never runs, [FirebaseAuth.getInstance] would throw,
 * and the UI needs a readable message instead of a crash.
 */
class FirebaseAuthRepository : AuthRepository {

    private val auth: FirebaseAuth? by lazy {
        runCatching { FirebaseAuth.getInstance() }.getOrNull()
    }

    private val _currentUser = MutableStateFlow<AuthUser?>(null)

    init {
        // Restore the offline presentation session before Firebase reports in,
        // so a restart mid-demo never flashes the sign-in screen.
        if (DemoSession.isActive) {
            _currentUser.value = demoUser()
        }
        auth?.addAuthStateListener { firebase ->
            // The learner's explicit choice wins: while a demo session is
            // active, a stale persisted Firebase session (or a later token
            // refresh) must never silently replace the presentation account.
            // signOut() clears the flag first, so the real user still wins
            // the moment the learner exits.
            _currentUser.value = if (DemoSession.isActive) {
                demoUser()
            } else {
                firebase.currentUser?.authUser()
            }
        }
    }

    override val currentUser: StateFlow<AuthUser?> = _currentUser.asStateFlow()

    override val isConfigured: Boolean
        get() = auth != null

    override suspend fun signInWithEmail(
        email: String,
        password: String,
    ): Result<AuthUser> = runCatching {
        val target = auth ?: throw notConfigured()
        target.signInWithEmailAndPassword(email, password).await().requireAuthUser()
    }

    override suspend fun signUpWithEmail(
        name: String,
        email: String,
        password: String,
    ): Result<AuthUser> = runCatching {
        val target = auth ?: throw notConfigured()
        target.createUserWithEmailAndPassword(email, password).await()
        target.currentUser?.updateProfile(
            UserProfileChangeRequest.Builder().setDisplayName(name.trim()).build(),
        )?.await()
        target.currentUser.requireAuthUser()
    }

    override suspend fun signInWithGoogle(context: Context): Result<AuthUser> = runCatching {
        val target = auth ?: throw notConfigured()
        val idToken = requestGoogleIdToken(context)
        val credential = GoogleAuthProvider.getCredential(idToken, null)
        target.signInWithCredential(credential).await().requireAuthUser()
    }.fold(
        onSuccess = { Result.success(it) },
        onFailure = { failure ->
            if (failure is GetCredentialCancellationException) {
                Result.failure(AuthCancelledException())
            } else {
                Result.failure(failure)
            }
        },
    )

    override fun continueAsDemo() {
        DemoSession.setActive(true)
        _currentUser.value = demoUser()
    }

    override fun signOut() {
        DemoSession.setActive(false)
        auth?.signOut()
        _currentUser.value = null
    }

    // ------------------------------------------------------------- google id

    /**
     * Runs the Credential Manager Google ID flow and returns a Firebase-ready
     * ID token.
     *
     * The server client ID is looked up reflectively: `default_web_client_id`
     * is generated by the Google Services plugin from google-services.json, so
     * a hard R reference would stop the project compiling before Firebase is
     * configured.
     */
    private suspend fun requestGoogleIdToken(context: Context): String {
        val clientIdRes = context.resources.getIdentifier(
            "default_web_client_id",
            "string",
            context.packageName,
        )
        check(clientIdRes != 0) {
            "Google Sign-In needs default_web_client_id from google-services.json."
        }
        val serverClientId = context.getString(clientIdRes)

        val option = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(false)
            .setServerClientId(serverClientId)
            .setAutoSelectEnabled(true)
            .build()

        val response = CredentialManager.create(context).getCredential(
            context = context,
            request = GetCredentialRequest.Builder()
                .addCredentialOption(option)
                .build(),
        )

        val credential = response.credential
        check(
            credential is CustomCredential &&
                credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL,
        ) {
            "Google Sign-In returned an unexpected credential."
        }
        return GoogleIdTokenCredential.createFrom(credential.data).idToken
    }

    // --------------------------------------------------------------- helpers

    private fun notConfigured(): Exception =
        IllegalStateException("Firebase isn't configured yet — add app/google-services.json.")

    /**
     * The seeded presentation learner. Email and uid are plain local values so
     * the profile screen can render them honestly without pretending a remote
     * account exists.
     */
    private fun demoUser() = AuthUser(
        uid = "demo-student",
        email = "demo@codequest.app",
        displayName = "Shekhar",
        isDemo = true,
    )

    private fun AuthResult?.requireAuthUser(): AuthUser =
        checkNotNull(this?.user) { "Firebase returned no user." }.authUser()

    private fun FirebaseUser?.requireAuthUser(): AuthUser =
        checkNotNull(this) { "Firebase returned no user." }.authUser()

    private fun FirebaseUser.authUser() = AuthUser(
        uid = uid,
        email = email,
        displayName = displayName,
    )

    private suspend fun <T> Task<T>.await(): T? =
        suspendCancellableCoroutine { continuation ->
            addOnSuccessListener { value -> continuation.resume(value) }
            addOnFailureListener { error -> continuation.resumeWithException(error) }
        }
}

/**
 * Human message for any auth failure, shared by the repository's callers.
 * [AuthCancelledException] is deliberately *not* handled here — the ViewModel
 * drops it silently instead of surfacing an error.
 */
fun Throwable.authMessage(): String = when (this) {
    is AuthMessageException -> message.orEmpty()
    is FirebaseAuthException -> friendlyAuthMessage(errorCode)
    is Resources.NotFoundException ->
        "Google Sign-In needs the web client ID from google-services.json."
    is IllegalStateException -> message?.takeIf { it.startsWith("Firebase") || it.startsWith("Google") }
        ?: "Sign-in failed. Please try again."
    is java.io.IOException -> "Network error — check your connection and retry."
    else -> message ?: "Sign-in failed. Please try again."
}

private fun friendlyAuthMessage(code: String): String = when (code) {
    "ERROR_INVALID_EMAIL" -> "That email address doesn't look right."
    "ERROR_MISSING_EMAIL" -> "Enter your email address."
    "ERROR_MISSING_PASSWORD" -> "Enter your password."
    "ERROR_WRONG_PASSWORD",
    "ERROR_INVALID_CREDENTIAL",
    "ERROR_USER_NOT_FOUND",
    -> "Email or password is incorrect."

    "ERROR_EMAIL_ALREADY_IN_USE" -> "An account already exists with that email."
    "ERROR_USER_DISABLED" -> "This account has been disabled."
    "ERROR_WEAK_PASSWORD" -> "Use at least 6 characters for the password."
    "ERROR_NETWORK" -> "Network error — check your connection and retry."
    "ERROR_TOO_MANY_REQUESTS" -> "Too many attempts. Please try again shortly."
    "ERROR_OPERATION_NOT_ALLOWED" ->
        "Email/password sign-in is disabled in the Firebase console."

    else -> "Sign-in failed. Please try again."
}

/** Wraps an already-human message so [authMessage] passes it through untouched. */
class AuthMessageException(message: String) : Exception(message)
